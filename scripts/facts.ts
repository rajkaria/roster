// Generates docs/FACTS.md from reports/. A fact whose source file or path is missing prints PENDING, never a number.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export type FactSpec = { key: string; file: string; path: string };

// Public numbers. Add a spec here before publishing a number anywhere.
export const FACT_SPECS: FactSpec[] = [
  { key: "SESSIONS_TOTAL", file: "review.json", path: "$.sessions.total" },
  { key: "FORWARD_PAIRS_N", file: "forward.json", path: "$.pairs.n" },
  { key: "FORWARD_MCNEMAR_P", file: "forward.json", path: "$.mcnemar.p" },
];

function tokens(path: string): (string | number)[] | undefined {
  if (!path.startsWith("$")) return undefined;
  const out: (string | number)[] = [];
  for (const m of path.slice(1).matchAll(/\.([^.[\]]+)|\[(\d+)\]/g)) out.push(m[2] !== undefined ? Number(m[2]) : (m[1] as string));
  return out;
}

export function lookup(data: unknown, path: string): number | string | boolean | undefined {
  const toks = tokens(path);
  if (!toks) return undefined;
  let cur: any = data;
  for (const t of toks) {
    if (cur === null || typeof cur !== "object" || !(t in cur)) return undefined;
    cur = cur[t];
  }
  return typeof cur === "number" || typeof cur === "string" || typeof cur === "boolean" ? cur : undefined;
}

export function renderFacts(reportsDir: string, specs: FactSpec[], ts: string): string {
  const lines = specs.map((s) => {
    const f = join(reportsDir, s.file);
    let value: number | string | boolean | undefined;
    if (existsSync(f)) {
      try {
        value = lookup(JSON.parse(readFileSync(f, "utf8")), s.path);
      } catch {
        value = undefined;
      }
    }
    return `${s.key} = ${value === undefined ? "PENDING" : value}  (source: reports/${s.file}#${s.path}, generated ${ts})`;
  });
  return [
    "<!-- GENERATED by scripts/facts.ts from reports/. Do not edit by hand. -->",
    "# Facts",
    "",
    ...lines,
    "",
  ].join("\n");
}

export function writeFacts(
  reportsDir = "reports",
  out = "docs/FACTS.md",
  specs = FACT_SPECS,
  ts = new Date().toISOString(),
): string {
  const text = renderFacts(reportsDir, specs, ts);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  return text;
}

if (import.meta.main) {
  writeFacts();
  console.log("wrote docs/FACTS.md");
}
