import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
  extractDesignHeadings,
  factLines,
  firstBlockquote,
  renderLlms,
} from "../scripts/llms";

const ROOT = join(import.meta.dir, "..");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");

const repoUrl = "https://github.com/rajkaria/roster";

function makeInput(overrides: Partial<Parameters<typeof renderLlms>[0]> = {}) {
  return {
    readme: "# Roster repo\n\n> First blockquote line\n> second blockquote line\n\nText.\n",
    designHeadings: ["Data model", "Gate (deterministic code)"],
    facts: "A = 1  (source: x#$.a)\nB = PENDING\n",
    repoUrl,
    ...overrides,
  };
}

describe("firstBlockquote", () => {
  test("takes only the first blockquote line", () => {
    expect(firstBlockquote("> one\n> two\n")).toBe("> one");
  });

  test("skips empty blockquote lines and finds a later one", () => {
    expect(firstBlockquote("title\n>\n> real\n")).toBe("> real");
  });

  test("returns undefined when there is no blockquote", () => {
    expect(firstBlockquote("# Title\n\nplain text\n")).toBeUndefined();
  });
});

describe("extractDesignHeadings", () => {
  test("lists headings below the title and strips closing hashes", () => {
    const md = "# Title\n\n## Overview\n\n### Sub ##\n\n#### Deep\n\n####### not a heading\n";
    expect(extractDesignHeadings(md)).toEqual(["Overview", "Sub", "Deep"]);
  });
});

describe("factLines", () => {
  test("drops the generated comment and title but keeps PENDING and sources", () => {
    const facts = "<!-- GENERATED by scripts/facts.ts -->\n# Facts\n\nA = 1  (source: x#$.a)\nB = PENDING\n";
    expect(factLines(facts)).toEqual(["A = 1  (source: x#$.a)", "B = PENDING"]);
  });
});

describe("renderLlms", () => {
  test("Roster title, then the README quote, then Docs, Design sections and Facts", () => {
    const out = renderLlms(makeInput());

    expect(out.startsWith("# Roster\n")).toBe(true);
    expect(out).toContain("> First blockquote line");
    expect(out).not.toContain("second blockquote line");
    expect(out.indexOf("## Docs")).toBeLessThan(out.indexOf("## Design sections"));
    expect(out.indexOf("## Design sections")).toBeLessThan(out.indexOf("## Facts"));
  });

  test("Docs links are absolute GitHub URLs and tolerate a trailing .git or slash", () => {
    const out = renderLlms(makeInput({ repoUrl: `${repoUrl}.git/` }));
    expect(out).toContain(`[docs/DESIGN.md](${repoUrl}/blob/main/docs/DESIGN.md)`);
    expect(out).toContain(`[experiments/PREREGISTRATION.md](${repoUrl}/blob/main/experiments/PREREGISTRATION.md)`);
    expect(out).toContain(`[docs/FACTS.md](${repoUrl}/blob/main/docs/FACTS.md)`);
  });

  test("omits the quote but keeps the sections when the README has no blockquote", () => {
    const out = renderLlms(makeInput({ readme: "# Roster repo\n" }));
    expect(out.startsWith("# Roster\n\n## Docs")).toBe(true);
  });

  test("generates from the repo's real files", () => {
    const out = renderLlms({
      readme: read("README.md"),
      designHeadings: extractDesignHeadings(read("docs/DESIGN.md")),
      facts: read("docs/FACTS.md"),
      repoUrl,
    });

    expect(out.startsWith("# Roster\n\n> Roster is an agent that runs performance reviews")).toBe(true);
    expect(out).toContain(`(${repoUrl}/blob/main/docs/FACTS.md)`);
    expect(out).toContain("- Gate (deterministic code; the coordinator can't override it)");
    expect(out).toContain("## Facts\n");
    expect(out).toContain("BACKLOG_SHA256 = ");
    expect(out).not.toContain("<!-- GENERATED");
    // A map, not the design document: only headings, never their bodies.
    expect(out).not.toContain("## Architecture\n\n- **Agent and CLI:**");
  });
});
